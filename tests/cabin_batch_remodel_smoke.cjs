/* 부하가 있는 선실을 여러 칸 한 번에 개조: 견적·취소·일괄 적용·재배치·짐칸 보호. */
'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('../tools/procedural_art/node_modules/playwright-core');
const ROOT = path.resolve(__dirname, '..'), OUT = path.join(ROOT, 'artifacts/cabin-batch-20261103');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXE || 'C:/Program Files/Google/Chrome/Application/chrome.exe',
    args: ['--no-sandbox', '--allow-file-access-from-files', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.route('https://fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
    await page.addInitScript(() => { requestAnimationFrame = () => 0; });
    await page.goto(pathToFileURL(path.join(ROOT, 'index.html')).href);
    await page.waitForFunction(() => window.G && G.CabinView && G.CrewAuto, null, { polling: 100 });
    const checks = await page.evaluate(async () => {
      await G.Game.ensureGeo(); G.Tutorial.active = () => false;
      const CB = G.Cabins, R = G.R, checks = [], ids = G.MATES.filter(d => !d.noWander && d.wage).slice(0, 8).map(d => d.id);
      const check = (ok, text) => { if (!ok) throw Error(text); checks.push(text); };
      window.batchFresh = () => {
        const s = G.State.newGame({ name: '선실 일괄 개조 검사', nation: 'PT', job: 'explorer', age: 25, birth: { m: 1, d: 1 }, st: { str: 60, int: 60, mar: 60, cha: 60 }, sk: {}, lg: [], diff: 'normal' });
        s.settings.res = .35; s.settings.autosave = false; s.flags.prologue = true; s.date = { y: 1520, m: 1, d: 1 }; s.player.gold = 1000000;
        s.fleet.ships = [R.newShip('hcarrack', '한번에 개조'), R.newShip('caravel', '보직 유지')];
        s.fleet.cargo = {}; s.fleet.food = s.fleet.water = s.fleet.mat = 0; s.mates = [];
        CB.rooms(); CB.remodel(1, 'galley'); CB.remodel(2, 'account'); CB.remodel(3, 'musicroom'); CB.remodel(4, 'store');
        s.mates = ids.slice(0, 6).map(id => ({ id, role: 'none', loyal: 80, sk: {} }));
        CB.place(s.mates[0], 1); CB.place(s.mates[1], 2); CB.place(s.mates[2], 3); CB.place(s.mates[3], 5);
        s.mates[4].role = 'nav'; s.mates[5].role = 'captain'; s.mates[5].ship = s.fleet.ships[1].uid; s.mates[5].capLock = 1;
        return s;
      };
      window.batchSnapshot = () => JSON.stringify({ rooms: CB.rooms(), mates: G.Game.state.mates, gold: G.Game.state.player.gold, day: G.Game.state.day });
      let s = batchFresh(), draft = CB.rooms().slice();
      [draft[1], draft[2]] = [draft[2], draft[1]];
      const before = batchSnapshot(), p = CB.planRemodel(draft);
      check(batchSnapshot() === before, '견적은 방·금화·날짜·부하를 바꾸지 않음');
      check(p.ok && p.cost === G.CABIN.account.cost + G.CABIN.galley.cost && p.days === G.CABIN.account.days + G.CABIN.galley.days, '변경한 방만 비용·기간 합산');
      const gold = s.player.gold, fixed = JSON.stringify(s.mates.slice(4));
      const applied = CB.remodelAll(draft);
      check(applied.ok && s.player.gold === gold - p.cost, '견적과 같은 금액을 한 번 차감');
      check(s.mates[0].room === 2 && s.mates[1].room === 1 && s.mates[1].role === 'purser' && s.mates[2].room === 3, '방을 맞바꿔도 같은 직무로 이동·경리 유지');
      check(JSON.stringify(s.mates.slice(4)) === fixed, '항해사·다른 배의 수동 선장 보직 유지');
      s = batchFresh(); draft = CB.rooms().slice(); draft[1] = 'store'; draft[4] = 'galley';
      s.fleet.cargo.pepper = { q: R.fleetCap(), cost: 10, from: 0, d: s.day };
      check(CB.remodelAll(draft).ok && s.mates[0].room === 4, '짐이 가득 차도 창고 위치 교환은 최종 짐칸 기준으로 허용');
      draft = CB.rooms().slice(); draft[1] = 'galley';
      let snapshot = batchSnapshot();
      check(!CB.remodelAll(draft).ok && batchSnapshot() === snapshot, '짐칸이 줄어 넘치면 전체 변경·결제를 취소');
      s = batchFresh(); draft = CB.rooms().slice(); draft[1] = 'rig'; s.player.gold = 0; snapshot = batchSnapshot();
      check(!CB.remodelAll(draft).ok && batchSnapshot() === snapshot, '돈이 부족하면 전체 변경 없음');
      s.player.gold = 1000000;
      const expected = { ship: CB.flagship(), rooms: CB.rooms().slice() }; CB.remodel(6, 'rec'); snapshot = batchSnapshot();
      check(!CB.remodelAll(draft, expected).ok && batchSnapshot() === snapshot, '편집 중 방이 달라지면 오래된 견적 적용 방지');
      draft = CB.rooms().slice(); draft[2] = 'captain'; snapshot = batchSnapshot();
      check(!CB.remodelAll(draft).ok && batchSnapshot() === snapshot, '고정 선실 지정은 전체 거부');
      s = batchFresh(); draft = CB.rooms().map((x, i) => i ? 'store' : x);
      const full = CB.remodelAll(draft);
      check(full.ok && full.idle === 3 && s.mates[1].role === 'none' && s.mates.filter(m => m.room != null).length === 1, '자리가 모자라면 갑판에 한 명·나머지 대기, 창고는 거주 금지');
      check(new Set(s.mates.filter(m => m.room != null).map(m => m.room)).size === s.mates.filter(m => m.room != null).length, '부하 한 방 한 명, 중복 배치 없음');
      const saved = batchSnapshot(); G.Game.state = G.State.deserialize(G.State.serialize());
      check(batchSnapshot() === saved, '저장·불러오기 뒤 선실·배치·금화 유지');
      batchFresh(); await G.Loader.hide(); G.CabinView.open({ yard: G.CITY_DATA[0] });
      return checks;
    });
    await page.locator('.cb-remodel-all').click();
    await page.locator('[data-remodel="1"]').selectOption('account');
    await page.locator('[data-remodel="2"]').selectOption('galley');
    assert((await page.locator('.cb-remodel-summary').innerText()).includes('변경 2칸 · 금화 2,100닢 · 공사 4일'));
    assert((await page.locator('[data-room="2"] .cb-remodel-person').innerText()).includes('1번에서 이동'));
    const beforeUI = await page.evaluate(() => batchSnapshot());
    await page.getByRole('button', { name: '견적 확인 후 개조', exact: true }).click();
    await page.getByRole('button', { name: '계속 편집', exact: true }).click();
    assert.equal(await page.evaluate(() => batchSnapshot()), beforeUI, '확인을 취소하면 편집 내용만 유지');
    await page.getByRole('button', { name: '취소', exact: true }).click();
    await page.locator('.cb-remodel-all').waitFor();
    assert.equal(await page.evaluate(() => batchSnapshot()), beforeUI, '편집 자체를 취소해도 변경 없음');
    await page.locator('.cb-remodel-all').click();
    await page.locator('.cb-remodel-fill').selectOption('musicroom');
    await page.locator('.cb-remodel-fill-btn').click();
    assert(await page.locator('[data-remodel]').evaluateAll(els => els.every(el => el.value === 'musicroom')));
    await page.locator('.cb-remodel-reset').click();
    assert.equal(await page.locator('[data-remodel="1"]').inputValue(), 'galley');
    await page.locator('[data-remodel="1"]').selectOption('account');
    await page.locator('[data-remodel="2"]').selectOption('galley');
    fs.mkdirSync(OUT, { recursive: true });
    await page.screenshot({ path: path.join(OUT, 'estimate.png') });
    const preApply = await page.evaluate(() => ({ gold: G.Game.state.player.gold, day: G.Game.state.day }));
    await page.evaluate(() => { window.batchPassCalls = []; const old = G.Game.passDays; G.Game.passDays = function (days) { batchPassCalls.push(days); return old.apply(this, arguments); }; G.UI.fade = async fn => fn(); });
    await page.getByRole('button', { name: '견적 확인 후 개조', exact: true }).click();
    await page.getByRole('button', { name: '한꺼번에 고친다', exact: true }).click();
    await page.locator('.cb-remodel-all').waitFor();
    const afterUI = await page.evaluate(() => ({ gold: G.Game.state.player.gold, day: G.Game.state.day, rooms: G.Cabins.rooms(), passCalls: batchPassCalls, purser: G.Game.state.mates.find(m => m.role === 'purser').room }));
    assert.equal(afterUI.gold, preApply.gold - 2100); assert.equal(afterUI.day, preApply.day + 4); assert.deepEqual(afterUI.passCalls, [4]);
    assert.equal(afterUI.rooms[1], 'account'); assert.equal(afterUI.rooms[2], 'galley'); assert.equal(afterUI.purser, 1);
    await page.screenshot({ path: path.join(OUT, 'completed.png') });
    await page.locator('.win .title .x').click();
    await page.evaluate(() => { G.CabinView.open(); });
    await page.locator('.cb-auto').waitFor(); assert.equal(await page.locator('.cb-remodel-all').count(), 0, '조선소 밖에는 일괄 개조 없음');
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(OUT, 'report.json'), JSON.stringify({ checks, ui: afterUI, errors }, null, 2));
    console.log('통과: ' + checks.length + '개 규칙 검사·실제 화면 편집/견적/취소/일괄 결제·부하 보직·저장·콘솔 오류 0');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
