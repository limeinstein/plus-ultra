/* 남는 부하를 빈 선실에 배치하고, 선실이 모자랄 때만 대기로 둔다. */
'use strict';
const assert = require('assert'), fs = require('fs'), path = require('path'), { pathToFileURL } = require('url');
const { chromium } = require('../tools/procedural_art/node_modules/playwright-core');
const ROOT = path.resolve(__dirname, '..'), OUT = path.join(ROOT, 'artifacts/empty-cabins-20261101');
fs.mkdirSync(OUT, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXE || 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--no-sandbox', '--allow-file-access-from-files', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.addInitScript(() => { requestAnimationFrame = () => 0; });
    await page.goto(pathToFileURL(path.join(ROOT, 'index.html')).href, { waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.waitForFunction(() => G.CrewAuto && G.CabinView && G.State, null, { polling: 100, timeout: 90000 });
    const checks = await page.evaluate(async () => {
      await G.Game.ensureGeo();
      G.Tutorial.active = () => false;
      const CA = G.CrewAuto, CB = G.Cabins, R = G.R, checks = [];
      const check = (value, text) => { if (!value) throw Error(text); checks.push(text); };
      const ids = G.MATES.filter(d => d.wage && !d.noWander).slice(0, 80).map(d => d.id);
      window.emptyCabinFresh = function (count) {
        G.State.newGame({ name: '빈 선실 시험', nation: 'PT', job: 'explorer', age: 30, birth: { m: 1, d: 1 }, st: { str: 60, int: 60, mar: 60, cha: 60 }, sk: {}, lg: [], diff: 'normal' });
        const s = G.Game.state;
        s.settings.autosave = false; s.settings.res = .35; s.date = { y: 1520, m: 1, d: 1 }; s.player.gold = 100000;
        s.fleet.ships = [R.newShip('caravel', '빈 선실 시험선')]; s.fleet.crew = 100;
        s.mates = []; CB.rooms();
        const n = count == null ? CB.rooms().length + 4 : count;
        for (let i = 0; i < n; i++) s.mates.push({ id: ids[i], role: i === 0 ? 'first' : 'none', loyal: 60, sk: Object.fromEntries(G.SKILLS.map(k => [k.id, 0])) });
        return s;
      };
      let s = emptyCabinFresh(), rooms = CB.rooms(), capacity = rooms.length;
      CA.refresh();
      check(rooms.slice(1).every((t, i) => t === 'hold' && CB.occupant(i + 1)), '기함의 빈 선실을 모두 한 명씩 채움');
      check(CA.idleCount() === s.mates.length - 1 - capacity, '갑판·빈 선실을 채운 뒤 남은 인원만 대기');
      check(s.mates[0].role === 'first' && s.mates[0].room == null, '기함 부관 보직 유지');
      check(new Set(s.mates.filter(m => m.room != null).map(m => m.room)).size === capacity, '한 선실에 한 명 / 중복 배치 없음');
      const stable = JSON.stringify(s.mates.map(m => [m.id, m.role, m.room]));
      CA.refresh(); check(JSON.stringify(s.mates.map(m => [m.id, m.role, m.room])) === stable, '반복 자동 채우기에도 배치 안정');
      const housed = s.mates.filter(m => m.roomType === 'hold'), idle = s.mates.filter(CA.idle);
      check(housed.every(m => CB.placeName(m) === '빈 선실' && R.roleName(m) === '빈 선실' && !CA.idle(m)), '빈 선실 거주자를 대기로 표시하지 않음');
      CB.tidy(); check(housed.every(m => m.room != null && m.roomType === 'hold'), '선실 정리 후 거주 배치 유지');
      check(housed.every(m => CB.powerAt(m.room) === 0) && CB.growSkill('hold') == null, '거주용 빈 선실은 직무 효과·특기 수련 없음');
      CB.monthly(false);
      check(housed.every(m => m.loyal === 60) && idle.every(m => m.loyal === 60 - G.BALANCE.mates.idleLoyal), '방이 없는 대기 인원만 월별 충성 하락');
      const savedRooms = s.mates.map(m => [m.id, m.room, m.roomType]);
      G.Game.state = G.State.deserialize(G.State.serialize()); s = G.Game.state; CA.refresh();
      check(JSON.stringify(s.mates.map(m => [m.id, m.room, m.roomType])) === JSON.stringify(savedRooms), '저장·불러오기 후 빈 선실 배치 보존');
      let m = s.mates.find(m => m.roomType === 'hold'), i = m.room;
      CB.remodel(i, 'galley'); check(m.room === i && m.roomType === 'galley', '거주 선실을 직무 선실로 개조하면 배치 유지');
      CB.remodel(i, 'hold'); check(m.room === i && m.roomType === 'hold', '직무 선실을 빈 선실로 바꿔도 거주 유지');
      CB.remodel(i, 'store'); check(m.room == null && !CB.occupant(i), '창고로 개조하면 거주 배치 해제');
      CB.place(m, i); check(m.room == null, '창고는 부하 배치 금지 유지');
      s = emptyCabinFresh(4); CA.refresh(); const cook = s.mates.find(m => m.roomType === 'hold'); cook.sk.cook = 3;
      const spot = cook.room === 1 ? 2 : 1, occupant = CB.occupant(spot);
      CB.remodel(spot, 'galley'); if (occupant) CB.place(occupant, null);
      CA.refresh(); check(cook.room === spot && cook.roomType === 'galley', '빈 선실 거주자도 빈 직무 선실에 적성대로 재배치');
      CA.autoAll(); check(cook.room === spot && CA.idleCount() === 0, '자동 배치도 직무 선실 우선 / 남은 인원은 빈 선실');
      s = emptyCabinFresh(); s.fleet.ships.push(R.newShip('caravel', '둘째 배'));
      const captain = s.mates[1]; captain.role = 'captain'; captain.ship = s.fleet.ships[1].uid; captain.capLock = 1;
      CA.refresh(); check(captain.role === 'captain' && captain.capLock && captain.ship === s.fleet.ships[1].uid, '손으로 정한 다른 배 선장 유지');
      check(['helm', 'deck', 'lookout'].every(post => CA.crewOf(s.fleet.ships[1])[post]), '다른 배의 직무도 거주용 빈 선실보다 우선');
      s = emptyCabinFresh(); CA.refresh();
      s.fleet.ships[0] = R.newShip('barca', '작은 새 기함'); CB.rooms(); R.tidyCaptains(); CA.refresh();
      check(s.mates.filter(m => m.room != null).every(m => m.room < CB.rooms().length && CB.occupant(m.room) === m), '작은 기함으로 변경해도 선실 정원·한 명 제한 준수');
      check(CA.idleCount() === Math.max(0, s.mates.length - 1 - CB.rooms().length), '기함 변경 후에도 빈 선실 우선·초과 인원만 대기');
      s = emptyCabinFresh(3); CA.refresh();
      s.loc = { mode: 'city', city: 0, lon: G.CITY_DATA[0].lon, lat: G.CITY_DATA[0].lat, via: 'sea' };
      window.__emptyCabinUi = G.CabinView.open(); await G.Loader.hide();
      return checks;
    });
    checks.forEach(x => console.log('통과: ' + x));
    await page.waitForSelector('.cb-card.hold', { state: 'visible' });
    const empty = await page.evaluate(() => {
      const card = [...document.querySelectorAll('.cb-card.hold')].find(c => !c.classList.contains('on'));
      const m = G.Game.state.mates.find(m => m.roomType === 'hold');
      window.__emptyCabinMove = { id: m.id, from: m.room, to: Number(card.dataset.i) };
      card.click(); return window.__emptyCabinMove;
    });
    assert(empty);
    await page.waitForSelector('.cb-pop');
    assert(!(await page.locator('.cb-pop').innerText()).includes('특기를 가진 부하가 없습니다'));
    await page.evaluate(() => [...document.querySelectorAll('.cb-pop-row[data-mate]')].find(r => r.dataset.mate === window.__emptyCabinMove.id).click());
    await page.waitForFunction(() => G.Game.state.mates.find(m => m.id === window.__emptyCabinMove.id).room === window.__emptyCabinMove.to, null, { polling: 100 });
    assert(await page.evaluate(() => !G.Cabins.occupant(window.__emptyCabinMove.from)));
    await page.waitForSelector('.cb-card.hold.on');
    await page.screenshot({ path: path.join(OUT, 'empty-cabin-residents.png') });
    await page.evaluate(() => [...document.querySelectorAll('.win .foot button')].find(b => b.textContent.includes('닫는다')).click());
    await page.waitForFunction(() => !document.querySelector('.cb-card'), null, { polling: 100 });
    assert.deepEqual(errors, [], '브라우저 오류 0');
    fs.writeFileSync(path.join(OUT, 'report.json'), JSON.stringify({ checks, ui: '빈 선실 팝업·수동 이동·표시 확인', errors }, null, 2));
    console.log('통과: 빈 선실 팝업·실제 부하 이동·브라우저 오류 0');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
