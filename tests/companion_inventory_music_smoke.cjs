/* 동료 물건 전달·보관·저장·음악실 악기 배율·나각 외형. */
'use strict';
const assert = require('assert/strict'), fs = require('fs'), path = require('path');
const { pathToFileURL } = require('url');
let chromium; try { ({ chromium } = require('playwright')); } catch (_) { ({ chromium } = require('../tools/procedural_art/node_modules/playwright-core')); }
const root = path.resolve(__dirname, '..'), out = path.join(root, 'artifacts/companion-instruments-20261101');
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXE || 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--no-sandbox', '--allow-file-access-from-files', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } }), errors = [];
  page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.addInitScript(() => { window.requestAnimationFrame = () => 0; });
  try {
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await page.waitForFunction(() => window.G && G.Game && G.Game.sceneName === 'title', null, { timeout: 120000 });
    const checks = await page.evaluate(async () => {
      await G.Game.ensureGeo();
      G.State.newGame({ name: '악기 전달 시험', nation: 'PT', job: 'explorer', age: 24, birth: { m: 1, d: 1 }, st: { str: 60, int: 60, mar: 60, cha: 60 }, sk: {}, lg: [], diff: 'normal' });
      const s = G.Game.state, R = G.R, CB = G.Cabins, checks = [];
      const ok = (v, name) => { if (!v) throw new Error(name); checks.push(name); };
      const near = (a, b) => Math.abs(a - b) < 1e-9;
      s.player.gold = 100000; s.settings.res = .35; s.settings.sound = 0; s.settings.music = 0;
      s.fleet.ships[0].type = 'galleon';
      CB.rooms(); for (let i = 1; i < 4; i++) CB.remodel(i, 'musicroom');
      const normal = { id: 'rocco', role: 'none', loyal: 100, sk: { music: 2 } };
      const bruno = { id: 'rosenthal', role: 'none', loyal: 100, joinedDay: s.day };
      const mermaid = { id: 'little_mermaid', role: 'none', loyal: 60, aff: 10 };
      s.mates = [normal, bruno, mermaid];
      s.player.items = [{ id: 'violin', qty: 3, buys: { 14: 2000 } }, { id: 'nagak', qty: 2, from: 190, paid: 1300 }, { id: 'longsword', qty: 2, from: 14, paid: 1100 }, { id: 'perfume', qty: 2 }, { id: 'brandy' }, { id: 'compass', name: '낡은 나침반', n: 2, legacy: true }, { id: 'ring' }];
      s.player.equip = { weapon: 'longsword', armor: null };
      ok(R.mateItems(normal).length === 0 && CB.musicInstrument(normal).mult === 1, '옛 저장의 소지품 없음·악기 없음');
      CB.place(mermaid, 1); const noInstrument = CB.fx('musicroom', 'musicroom');
      ok(noInstrument > 0 && CB.musicInstrument(mermaid).mult === 1, '제독의 악기만으로 동료 효과가 오르지 않음');
      let v = s.player.items.find(x => x.id === 'violin');
      R.giveMateItem(normal, v); R.giveMateItem(bruno, v); R.giveMateItem(bruno, v);
      ok(R.itemCount('violin') === 0 && normal.items[0].qty === 1 && bruno.items[0].qty === 2 && bruno.items[0].buys[14] === 2000, '묶음에서 한 개씩 전달·동료 묶음·치른 값 보존');
      R.giveMateItem(mermaid, s.player.items.find(x => x.id === 'nagak'));
      ok(mermaid.items[0].from === 190 && mermaid.items[0].paid === 1300 && R.itemCount('nagak') === 1, '나각 한 개 보관·산 도시와 값 보존');
      ok(near(CB.fx('musicroom', 'musicroom'), noInstrument * 3), '인어공주 나각: 실제 음악실 효과 정확히 3배');
      R.giveMateItem(mermaid, s.player.items.find(x => x.id === 'longsword'));
      ok(mermaid.items.some(x => x.id === 'longsword') && R.itemCount('longsword') === 1 && s.player.equip.weapon === 'longsword', '여성 부하도 무기 보관·제독 착용 장비 유지');
      ok(!R.giveMateItem(mermaid, s.player.items.find(x => x.id === 'longsword')), '착용 중인 마지막 장비 전달 방지');
      const named = s.player.items.find(x => x.name === '낡은 나침반'); R.giveMateItem(bruno, named);
      ok(bruno.items.some(x => x.name === '낡은 나침반' && x.n === 2 && x.legacy), '이름·사용 횟수·개별 상태 보존');
      const proof = { id: 'excalibur', disc: 'test_proof', evidence: true }; s.player.items.push(proof);
      ok(!R.giveMateItem(bruno, proof) && !R.giveMateItem(bruno, s.player.items.find(x => x.id === 'ring')), '미보고 증거품·청혼 반지 보존');
      CB.place(mermaid, null); CB.place(normal, 1);
      const normHeld = normal.items; normal.items = []; const normalBase = CB.fx('musicroom', 'musicroom'); normal.items = normHeld;
      ok(near(CB.fx('musicroom', 'musicroom'), normalBase * 1.5), '일반 동료의 악기: 실제 음악실 효과 1.5배');
      CB.place(normal, null); CB.place(bruno, 1);
      const brunoHeld = bruno.items; bruno.items = []; const brunoBase = CB.fx('musicroom', 'musicroom'); bruno.items = brunoHeld;
      ok(near(CB.fx('musicroom', 'musicroom'), brunoBase * 3), '브루노 바이올린: 상한에 눌리지 않고 정확히 3배');
      bruno.items.push({ id: 'guitar', qty: 20 });
      ok(near(CB.fx('musicroom', 'musicroom'), brunoBase * 3), '악기 수량·종류 중첩 없음');
      bruno.items = [{ id: 'nagak' }]; ok(near(CB.fx('musicroom', 'musicroom'), brunoBase * 1.5), '브루노도 전용 악기 이외에는 1.5배'); bruno.items = brunoHeld;
      const rooms = CB.rooms(); rooms[1] = 'rec'; bruno.roomType = 'rec'; const recHeld = CB.fx('rec', 'rec'); bruno.items = [];
      ok(near(CB.fx('rec', 'rec'), recHeld), '악기는 음악실 외의 방 효과에 영향 없음'); bruno.items = brunoHeld; rooms[1] = 'musicroom'; bruno.roomType = 'musicroom';
      CB.place(mermaid, 2); const withInstruments = CB.fx('musicroom', 'musicroom'), mh = mermaid.items; bruno.items = []; mermaid.items = [];
      const cappedBase = CB.fx('musicroom', 'musicroom'); bruno.items = brunoHeld; mermaid.items = mh;
      ok(near(withInstruments, cappedBase * 3), '복수 음악실: 기존 기본 상한 뒤 전용 악기 배율 적용');
      const loaded = G.State.deserialize(G.State.serialize());
      ok(loaded.mates.find(x => x.id === 'rosenthal').items.some(x => x.id === 'violin' && x.qty === 2 && x.buys[14] === 2000), '저장 복원 시 동료 소지품·수량·치른 값 유지');
      await G.Img.preload([G.Img.chain.item(G.ITEM.nagak)]);
      ok(G.Img.pick(G.Img.chain.item(G.ITEM.nagak)) === 'items/nagak' && G.Img.get('items/nagak').naturalWidth === 256, '나각 전용 256px 원화 연결');
      G.Game.go('city', { cityId: 190, load: true });
      return checks;
    });
    await page.waitForFunction(() => G.Game.sceneName === 'city');
    await page.evaluate(() => { G.Info.open('mates'); });
    await page.locator('[data-mate="little_mermaid"] .mb-person').click();
    await page.locator('.mb-owned-item[data-item="nagak"]').waitFor();
    assert(await page.locator('[data-action="give-item"]').evaluate(el => { const r = el.getBoundingClientRect(), box = el.closest('.mb-body').getBoundingClientRect(); return r.top >= box.top && r.bottom <= box.bottom + 1; }), '물건 전달 단추가 스크롤 없이 화면 안에 있음');
    assert((await page.locator('.mb-owned').innerText()).includes('3배'));
    const before = await page.evaluate(() => { const m = G.Game.state.mates.find(x => x.id === 'little_mermaid'); return { aff: m.aff, loyal: m.loyal, craft: G.R.skill('craft') }; });
    await page.locator('[data-action="give-item"]').click();
    await page.locator('.choice').filter({ hasText: /^향수/ }).click();
    await page.waitForFunction(() => G.R.itemCount('perfume') === 1);
    assert(await page.evaluate(b => { const m = G.Game.state.mates.find(x => x.id === 'little_mermaid'); return !m.items.some(x => x.id === 'perfume') && m.aff === Math.min(100, b.aff + G.ITEM.perfume.gv + b.craft) && m.loyal > b.loyal; }, before));
    await page.locator('[data-action="give-item"]').click();
    await page.locator('.choice').filter({ hasText: /^나각/ }).click();
    await page.waitForFunction(() => G.R.itemCount('nagak') === 0);
    assert.equal(await page.locator('.mb-owned-item[data-item="nagak"] .mb-owned-qty').innerText(), '×2');
    assert.equal(await page.locator('.mb-owned-item[data-item="perfume"]').count(), 0);
    await page.evaluate(async () => { await G.Img.preload(G.R.mateItems(G.Game.state.mates.find(m => m.id === 'little_mermaid')).map(it => G.Img.chain.item(G.ITEM[it.id]))); });
    await page.screenshot({ path: path.join(out, 'mermaid-owned-nagak.png') });
    await page.locator('.mb-nav-person[data-mate="rosenthal"]').click();
    assert((await page.locator('.mb-owned').innerText()).includes('바이올린 효과 3배'));
    await page.evaluate(async () => { await G.Img.preload(G.R.mateItems(G.Game.state.mates.find(m => m.id === 'rosenthal')).map(it => G.Img.chain.item(G.ITEM[it.id]))); });
    await page.screenshot({ path: path.join(out, 'bruno-owned-violin.png') });
    await page.locator('.win .title .x').click();
    const final = await page.evaluate(async () => {
      const s = G.Game.state, m = s.mates.find(x => x.id === 'rosenthal'), expected = JSON.stringify(m.items), confirm = G.UI.confirm, chance = G.U.chance;
      try { G.UI.confirm = async () => true; G.U.chance = () => false; await G.MateDismiss.fire(m, G.CITY_DATA[190]); } finally { G.UI.confirm = confirm; G.U.chance = chance; }
      if (JSON.stringify(G.MateDismiss.record(m.id).kept.items) !== expected) throw new Error('해고 시 소지품 보존');
      const rehired = { id: m.id, role: 'none', loyal: 70 }; s.mates.push(rehired); G.MateDismiss.hired(rehired);
      if (JSON.stringify(rehired.items) !== expected) throw new Error('재등용 시 소지품 복원');
      return { keptOnRehire: true, nagakQty: s.mates.find(x => x.id === 'little_mermaid').items.find(x => x.id === 'nagak').qty, musicMultiplier: G.Cabins.musicInstrument(rehired).mult };
    });
    await page.evaluate(() => {
      const MK = G.Scenes.city.B.market, s = G.Game.state; let attempts = 0;
      while (!MK.stock(G.CITY_DATA[190]).some(it => it.id === 'nagak') && attempts++ < 20) s.day += 45;
      if (!MK.stock(G.CITY_DATA[190]).some(it => it.id === 'nagak')) throw new Error('나각 시장 입고');
      G.Scenes.city.say = async () => {}; MK.buy(G.CITY_DATA[190]);
    });
    await page.locator('.choice-cats [data-cat="instrument"]').click();
    await page.locator('.choice:visible').filter({ hasText: /^나각 / }).click();
    await page.locator('.win .nfield').fill('1');
    await page.locator('.win .foot .btn.navy').click();
    await page.locator('.item-show img').evaluate(el => el.decode());
    assert((await page.locator('.item-show img').getAttribute('src')).endsWith('/items/nagak.webp'));
    await page.screenshot({ path: path.join(out, 'nagak-market.png') });
    await page.locator('.win .foot .btn.navy').click();
    await page.waitForFunction(() => G.R.itemCount('nagak') === 1);
    await page.locator('.choices').waitFor(); await page.locator('.win .title .x').click();
    await page.goto(pathToFileURL(path.join(root, 'catalog.html')).href + '#items');
    await page.locator('[data-chip="instrument"]').click(); await page.locator('#q').fill('나각');
    await page.locator('#grid .card .name').filter({ hasText: /^나각$/ }).click();
    await page.locator('#dHero canvas').waitFor();
    assert.equal(await page.evaluate(() => G.Img.pick(G.Img.chain.item(G.ITEM.nagak))), 'items/nagak');
    await page.screenshot({ path: path.join(out, 'nagak-catalog.png') });
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify({ checks, uiGiftConsumed: true, uiNagakStored: true, ...final, errors }, null, 2));
    console.log('통과: 동료 전달·보관·수량·증거/장비 보호·저장·재등용·음악실 1.5/3배·중첩 방지·나각 외형·실제 수첩 조작·콘솔 오류 0');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
